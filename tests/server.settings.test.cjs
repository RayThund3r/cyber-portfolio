const H = require('./server-setup.cjs');
let fail = 0; const ok = (n, c, x = '') => { console.log((c ? 'PASS ' : 'FAIL ') + n + (x ? ' ' + x : '')); if (!c) fail++; };
(async () => {
  process.env.DATA_DIR = require('fs').mkdtempSync(require('path').join(require('os').tmpdir(), 'set-'));
  const S = H.req('lib/siteSettings'), St = H.req('server/store'), SC = H.req('utils/chatEngine/siteConfig');
  let n = S.normalizeSettings({ social: { instagram: 'javascript:alert(1)', facebook: '@mybrand', x: 'https://x.com/me' }, business: { email: 'bad', whatsapp: '+256 700-000 000', name: 'A'.repeat(200) }, evil: 1 });
  ok('script-scheme social dropped', n.social.instagram === '');
  ok('handle cleaned, https kept', n.social.facebook === 'mybrand' && n.social.x === 'https://x.com/me');
  ok('bad email dropped, whatsapp digits only, name capped', n.business.email === '' && n.business.whatsapp === '256700000000' && n.business.name.length === 60);
  ok('unknown keys dropped; defaults on', !('evil' in n) && n.features.chat === true && n.maintenance.enabled === false);
  ok('garbage input yields defaults', JSON.stringify(S.normalizeSettings(null)) === JSON.stringify(S.DEFAULT_SETTINGS));
  ok('empty store gives defaults', (await St.getSiteSettings()).maintenance.enabled === false);
  const saved = await St.saveSiteSettings({ maintenance: { enabled: true, message: 'Back soon' }, features: { chat: false } });
  const back = await St.getSiteSettings();
  ok('save → read round-trips', back.maintenance.enabled && back.maintenance.message === 'Back soon' && back.features.chat === false && saved.features.chat === false);
  const w = SC.SITE.whatsapp; SC.applySiteOverrides({ whatsapp: '256711111111' });
  ok('override applies', SC.SITE.whatsapp === '256711111111'); SC.applySiteOverrides({});
  ok('empty override restores built-in', SC.SITE.whatsapp === w);
  // optional features: OFF by default, and the price is untouched until smart pricing is switched on
  ok('optional features default OFF', S.DEFAULT_SETTINGS.features.smartPricing === false && S.DEFAULT_SETTINGS.features.dragDrop === false && S.normalizeSettings({}).features.smartPricing === false);
  ok('only literal true switches them on', S.normalizeSettings({ features: { smartPricing: 'yes', dragDrop: 1 } }).features.smartPricing === false && S.normalizeSettings({ features: { dragDrop: true } }).features.dragDrop === true);
  const P = H.req('server/projects'), B = H.req('server/builderUtil');
  const tpls = await St.getTemplates(); const tpl = tpls.find((t) => t.priceUSD > 0 || t.priceUGX > 0) || tpls[0];
  global.fetch = async () => { throw new Error('offline'); };
  await St.saveSiteSettings({ features: { smartPricing: false } });
  const off = await P.priceNow(tpl.id), offCfg = await P.priceNow(tpl.id, tpl.config);
  ok('smart OFF: price identical with or without the site contents', off === offCfg, off + ' ' + offCfg);
  await St.saveSiteSettings({ features: { smartPricing: true } });
  const on = await P.priceNow(tpl.id, tpl.config);
  ok('smart ON: price is a number not below the template price', typeof on === 'number' && (off === null || on >= off), off + ' → ' + on);
  const rich = JSON.parse(JSON.stringify(tpl.config)); for (let i = 0; i < 8; i++) rich.sections.push(JSON.parse(JSON.stringify(rich.sections.find((x) => x.type !== 'navbar' && x.type !== 'footer') || rich.sections[0])));
  ok('smart ON: a bigger site costs more', (await P.priceNow(tpl.id, rich)) > on);
  await St.saveTemplates([{ ...tpl, id: 'free-t', priceUGX: 0, priceUSD: null }, tpl]);
  ok('smart ON: a free template stays free', (await P.priceNow('free-t', rich)) === 0);
  const sm = H.req('lib/builder/smartPricing'); const c = sm.normalizeRateCard({ base: -5, perImage: 'x' });
  ok('rate card is sanitised', c.base === sm.DEFAULT_RATE_CARD.base && c.perImage === sm.DEFAULT_RATE_CARD.perImage);
  await St.saveSiteSettings({});
  process.exit(fail ? 1 : 0);
})();
