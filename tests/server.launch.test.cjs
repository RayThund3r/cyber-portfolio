const path = require('path'); const L = require(path.join(__dirname, '.build-server/lib/admin/launch.js'));
let fail = 0; const ok = (n, c, x = '') => { console.log((c ? 'PASS ' : 'FAIL ') + n + (x ? ' ' + x : '')); if (!c) fail++; };
const none = { storeConfigured: false, aiAvailable: false, totp: false, passwordLen: 0, secretLen: 0 };
let m = L.missions({}, none), r = L.readiness(m);
ok('empty env scores 0 and is GROUNDED', r.score === 0 && r.level === 'GROUNDED', JSON.stringify([r.score, r.level]));
ok('next mission is the heaviest required one (storage)', r.next && r.next.id === 'store');
ok('weights add to 100', m.reduce((a, x) => a + x.weight, 0) === 100);
m = L.missions({ RESEND_API_KEY: 're_x', NEXT_PUBLIC_SITE_URL: 'https://a.b', MOMO_MTN_NUMBER: '0700', TURNSTILE_SECRET_KEY: 's', NEXT_PUBLIC_TURNSTILE_SITE_KEY: 'k' }, { storeConfigured: true, aiAvailable: true, totp: true, passwordLen: 14, secretLen: 40 });
r = L.readiness(m); ok('everything set → 100 and FULLY ARMED, no next', r.score === 100 && r.level === 'FULLY ARMED' && r.next === null);
m = L.missions({ NEXT_PUBLIC_SITE_URL: 'http://localhost:3000' }, none); ok('localhost address does not count', !m.find((x) => x.id === 'url').done);
m = L.missions({ RESEND_API_KEY: '   ' }, none); ok('blank value does not count', !m.find((x) => x.id === 'mail').done);
const json = JSON.stringify(L.missions({ RESEND_API_KEY: 'SECRET123', NEXT_PUBLIC_SITE_URL: 'https://x.y' }, none));
ok('no secret values leak into the output', !json.includes('SECRET123'));
// things saved in the panel count: no Vercel variable should be demanded for them
m = L.missions({}, { ...none, storeConfigured: true, passwordSaved: true, totp: true, payConfigured: true, siteUrl: 'https://my.site' });
ok('panel-saved password + permanent storage satisfies the login mission', m.find((x) => x.id === 'login').done);
ok('panel-saved two-factor counts', m.find((x) => x.id === '2fa').done);
ok('payment details saved in the panel count', m.find((x) => x.id === 'pay').done);
ok('site address is detected from the request', m.find((x) => x.id === 'url').done);
ok('none of those missions asks for an env variable any more', ['pay', 'url'].every((id) => m.find((x) => x.id === id).env.length === 0));
m = L.missions({}, { ...none, passwordLen: 14, secretLen: 0, storeConfigured: false });
ok('without storage a session secret is still needed', !m.find((x) => x.id === 'login').done);
m = L.missions({}, { ...none, siteUrl: 'http://localhost:3000' });
ok('a localhost request does not count as a public address', !m.find((x) => x.id === 'url').done);
(async () => {
  global.fetch = async () => { throw new Error('offline'); };
  process.env.DATA_DIR = process.env.DATA_DIR || require('os').tmpdir();
  const LC = require('./server-setup.cjs').req('lib/admin/liveChecks');
  const calls = [];
  const fake = async (url, init) => { calls.push(String(url)); if (/resend/.test(url)) return new Response(init.headers.Authorization.includes('good') ? '{}' : '{"message":"invalid"}', { status: init.headers.Authorization.includes('good') ? 200 : 401 }); return new Response('{}', { status: 200 }); };
  let c = await LC.runLiveChecks({ RESEND_API_KEY: 're_good', NEXT_PUBLIC_SITE_URL: 'https://x.example' }, fake);
  const by = (id) => c.find((x) => x.id === id);
  ok('live: storage round-trips', by('storage').ok === true, by('storage').detail);
  ok('live: resend valid key', by('resend').ok === true);
  ok('live: site address is probed', by('site').ok === true && calls.some((u) => u === 'https://x.example/api/health'));
  ok('live: web check fails gracefully offline', by('web').ok === false && /Wikipedia|confident/.test(by('web').detail), by('web').detail);
  c = await LC.runLiveChecks({ RESEND_API_KEY: 're_bad', NEXT_PUBLIC_SITE_URL: 'http://localhost:3000' }, fake);
  ok('live: bad resend key flagged with a fix', by('resend').ok === false && !!by('resend').fix);
  ok('live: non-https site address is "not set up"', by('site').ok === null);
  c = await LC.runLiveChecks({}, fake);
  ok('live: missing resend key is "not set up", never a failure', by('resend').ok === null);
  ok('live: output never contains the key', !JSON.stringify(await LC.runLiveChecks({ RESEND_API_KEY: 're_good_SECRETXYZ' }, fake)).includes('SECRETXYZ'));
  const D = require('./server-setup.cjs').req('server/llmProviders').detectProvider;
  ok('key prefixes are recognised', D('gsk_' + 'a'.repeat(40)) === 'groq' && D('AIza' + 'b'.repeat(35)) === 'gemini' && D('sk-or-v1-' + 'c'.repeat(30)) === 'openrouter' && D('csk-' + 'd'.repeat(30)) === 'cerebras');
  ok('unknown, short or hostile keys are not guessed', D('hello') === null && D('') === null && D('gsk_short') === null && D('sk-' + 'x'.repeat(40)) === null);
  process.exit(fail ? 1 : 0);
})();
