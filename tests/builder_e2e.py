import subprocess, time, os, json, re, sys
from playwright.sync_api import sync_playwright
DATA = subprocess.check_output(['mktemp','-d']).decode().strip()
env = dict(os.environ, DATA_DIR=DATA, PORT='4011')
srv = subprocess.Popen(['node','/tmp/harness_server.cjs'], env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT); time.sleep(1.2)
BASE='http://localhost:4011'
def ok(label, v, extra=''): print(('PASS' if v else 'FAIL')+'  '+label, extra); return v
results=[]
try:
  with sync_playwright() as p:
    b = p.chromium.launch()
    def newpage(ctx=None, init=None):
        c = ctx or b.new_context(viewport={'width':1280,'height':900})
        pg = c.new_page(); errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)[:140]))
        pg.on('console', lambda m: errs.append('console:'+m.text[:140]) if m.type=='error' and 'Failed to load resource' not in m.text else None)
        if init: pg.add_init_script(init)
        return c, pg, errs
    print('=== 1. builder home')
    ctx, pg, errs = newpage(); pg.goto(BASE+'/builder'); pg.wait_for_selector('text=Start from scratch', timeout=8000); pg.wait_for_timeout(600)
    ok('big "Start from scratch" button', pg.locator('button:has-text("Start from scratch")').count()>=1)
    ok('"Choose a template" button', pg.locator('button:has-text("Choose a template")').count()==1)
    ok('welcome guide shown on first visit', pg.locator('text=New here? It takes three steps').count()==1)
    cards = pg.locator('article').count(); ok(f'blank card + 4 templates = 5 cards (got {cards})', cards==5)
    pg.click('button:has-text("Got it")'); ok('guide dismissed', pg.locator('text=New here?').count()==0)
    pg.reload(); pg.wait_for_selector('text=Start from scratch'); pg.wait_for_timeout(400); ok('…and stays dismissed after reload', pg.locator('text=New here?').count()==0 and pg.locator('text=How does this work?').count()==1)
    print('=== 2. start from scratch -> editor (React dev double-effect is ON)')
    pg.click('button:has-text("✨ Start from scratch")'); pg.wait_for_selector('[data-tour=name]', timeout=10000); pg.wait_for_timeout(700)
    ok('editor opened (no "couldn\'t find that project" dead end)', pg.locator('[data-tour=name]').count()==1 and pg.locator("text=couldn't find").count()==0)
    ok('secret key removed from the address bar', 'key=' not in pg.url and 'id=PRJ-' in pg.url, pg.url)
    srcdoc = pg.evaluate("document.querySelector('iframe[title=\"Live preview of your website\"]').getAttribute('srcdoc')||''")
    ok('preview shows the blank starter headline', 'Your headline goes here' in srcdoc)
    ok('"your page is just getting started" hint for blank sites', pg.locator('text=Your page is just getting started').count()==1)
    print('=== 3. guided tour')
    pg.wait_for_selector('text=STEP 1 OF', timeout=5000); ok('tour starts by itself on first visit', True)
    titles=[]
    for i in range(10):
        t = pg.locator('[role=dialog][aria-label="Quick tour"] h2').inner_text(); titles.append(t)
        btn = pg.locator('[role=dialog][aria-label="Quick tour"] button:has-text("Next"), [role=dialog][aria-label="Quick tour"] button:has-text("Done")').first
        last = btn.inner_text()=='Done'; btn.click(); pg.wait_for_timeout(450)
        if last: break
    ok(f'tour walked through {len(titles)} steps: ' + ' | '.join(titles), len(titles)>=6)
    ok('tour closed and remembered', pg.locator('[role=dialog][aria-label="Quick tour"]').count()==0 and pg.evaluate("localStorage.getItem('sys_builder_tour_done')")=='1')
    pg.click('button:has-text("❓ Tour")'); pg.wait_for_selector('text=STEP 1 OF'); pg.keyboard.press('Escape'); pg.wait_for_timeout(300); ok('❓ Tour button replays it; Esc closes', pg.locator('[role=dialog][aria-label="Quick tour"]').count()==0)
    print('=== 4. reload without the key (the old dead end)')
    url_no_key = pg.url; pg.reload(); pg.wait_for_selector('[data-tour=name]', timeout=10000); pg.wait_for_timeout(500)
    ok('reloading ?id=… (no key in URL) still opens the site', pg.locator('[data-tour=name]').count()==1 and pg.locator("text=couldn't find").count()==0, url_no_key)
    for i in range(5): pg.reload(); pg.wait_for_selector('[data-tour=name]', timeout=10000)
    ok('5 more reloads: still fine (never locked out)', pg.locator('[data-tour=name]').count()==1)
    print('=== 5. editing, adding a section, autosave')
    pg.click('button:has-text("+ Add a section")'); pg.wait_for_timeout(300)
    opts = pg.locator('button:has-text("Services")'); ok('section picker opens', opts.count()>=1)
    opts.first.click(); pg.wait_for_timeout(2600)
    srcdoc = pg.evaluate("document.querySelector('iframe[title=\"Live preview of your website\"]').getAttribute('srcdoc')||''")
    ok('new Services section appears in the preview', 'What we offer' in srcdoc)
    ok('autosave reported "Saved"', pg.locator('text=/Saved/').count()>=1, pg.locator('text=/Saved/').first.inner_text() if pg.locator('text=/Saved/').count() else '')
    project_id = re.search(r'id=(PRJ-[A-Z0-9]+)', pg.url).group(1)
    stored = pg.evaluate("JSON.parse(localStorage.getItem('sys_builder_projects')||'[]')"); key = stored[0]['key']
    print('=== 6. a second tab edits the same site (conflict)')
    ctxB, pgB, _ = newpage(); pgB.goto(f'{BASE}/builder/edit?id={project_id}&key={key}'); pgB.wait_for_selector('[data-tour=name]', timeout=10000); pgB.wait_for_timeout(800)
    pgB.locator('[data-tour=name]').fill('Edited in tab B'); pgB.wait_for_timeout(2600)
    pg.locator('[data-tour=name]').fill('Edited in tab A (stale)'); pg.wait_for_timeout(2800)
    ok('stale tab shows the conflict banner', pg.locator('text=changed somewhere else').count()>=1)
    pg.click('button:has-text("Load the newer version")'); pg.wait_for_selector('[data-tour=name]', timeout=10000); pg.wait_for_timeout(600)
    ok('"Load the newer version" shows tab B\'s change', pg.locator('[data-tour=name]').input_value()=='Edited in tab B', pg.locator('[data-tour=name]').input_value())
    ctxB.close()
    print('=== 7. blocked browser storage (private mode)')
    blocker = "Object.defineProperty(window,'localStorage',{get(){throw new DOMException('blocked','SecurityError')}});Object.defineProperty(window,'sessionStorage',{get(){throw new DOMException('blocked','SecurityError')}});"
    ctxC, pgC, errC = newpage(init=blocker); pgC.goto(f'{BASE}/builder/edit?id={project_id}&key={key}'); pgC.wait_for_selector('[data-tour=name]', timeout=10000); pgC.wait_for_timeout(600)
    ok('opens even with storage blocked', pgC.locator('[data-tour=name]').count()==1)
    ok('key is KEPT in the URL (so a reload still works)', 'key=' in pgC.url)
    pgC.reload(); pgC.wait_for_selector('[data-tour=name]', timeout=10000); ok('reload works with storage blocked', pgC.locator('[data-tour=name]').count()==1)
    ctxC.close()
    print('=== 8. unknown device / lost key -> recovery screen')
    ctxD, pgD, _ = newpage(); pgD.goto(f'{BASE}/builder/edit?id={project_id}'); pgD.wait_for_selector('text=We need your edit link', timeout=8000)
    ok('friendly recovery screen instead of a dead end', pgD.locator('input#edit-link').count()==1)
    pgD.fill('input#edit-link', 'garbage'); pgD.click('button:has-text("OPEN MY SITE")'); ok('bad text gets a clear message', pgD.locator('[role=alert]').count()==1)
    pgD.fill('input#edit-link', f'{BASE}/builder/edit?id={project_id}&key={key}'); pgD.click('button:has-text("OPEN MY SITE")'); pgD.wait_for_selector('[data-tour=name]', timeout=10000)
    ok('pasting the edit link opens the site', pgD.locator('[data-tour=name]').count()==1)
    ctxD.close()
    print('=== 9. template list down -> built-in fallback')
    ctxE = b.new_context(viewport={'width':1280,'height':900}); pgE = ctxE.new_page(); pgE.route('**/api/builder/templates', lambda r: r.fulfill(status=500, body='{}'))
    pgE.goto(BASE+'/builder'); pgE.wait_for_selector('text=We could not reach the live template list', timeout=8000)
    ok('still shows blank + built-in templates (never empty)', pgE.locator('article').count()==5)
    ctxE.close()
    print('=== 10. delete my site')
    pg.goto(BASE+'/builder'); pg.wait_for_selector('text=YOUR PROJECTS ON THIS DEVICE', timeout=8000)
    pg.once('dialog', lambda d: d.accept()); pg.click('button:has-text("Delete site")'); pg.wait_for_timeout(900)
    ok('site deleted and removed from the list', pg.locator('text=YOUR PROJECTS ON THIS DEVICE').count()==0 or project_id not in pg.content())
    ctxF, pgF, _ = newpage(); pgF.goto(f'{BASE}/builder/edit?id={project_id}&key={key}'); pgF.wait_for_selector('[role=alert]', timeout=8000); ok('opening the deleted site shows a clear message + way out', pgF.locator('text=Back to the builder').count()==1); ctxF.close()
    print('\nbrowser errors on main page:', errs or 'none')
    b.close()
finally:
  srv.terminate()
