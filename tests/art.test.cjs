const H = require('./server-setup.cjs');
let fail = 0; const ok = (n, c) => { console.log((c ? 'PASS ' : 'FAIL ') + n); if (!c) fail++; };
const png = 'data:image/png;base64,' + Buffer.from('89504e470d0a1a0a0000000d49484452', 'hex').toString('base64');
const rejects = async (p) => { try { await p; return false; } catch { return true; } };
(async () => {
  const A = H.req('server/art'); const A0 = A;
  const D = H.req('server/artDemo');
  const di = D.demoItems();
  ok('sample pieces: 14, each with a valid svg and hex colours', di.length === 14 && di.every((x) => (D.demoSvg(x.id) || '').startsWith('<svg') && /^#[0-9a-f]{6}$/.test(x.color) && x.w > 0 && x.h > 0) && D.demoSvg('nope') === null);
  ok('sample ids survive cleanId', di.every((x) => A0.cleanId(x.id) === x.id));
  ok('starts empty', (await A.listArt()).length === 0);
  let l = await A.saveArt({ item: { title: 'Logo for Kato Salon', category: 'Logos', tools: 'Illustrator, Photoshop', year: '2026x', description: '<b>Hi</b>' }, image: png, thumb: png, w: 1200, h: 800 });
  const a = l[0];
  ok('saved with clean fields', l.length === 1 && a.title === 'Logo for Kato Salon' && a.category === 'Logos' && a.tools.length === 2 && a.year === '2026' && !a.description.includes('<') && a.w === 1200 && a.v === 1);
  const img = await A.getArtImage(a.id, false);
  ok('picture comes back as bytes with its type', img && img.type === 'image/png' && img.bytes.length > 8);
  ok('thumbnail is served too', !!(await A.getArtImage(a.id, true)));
  ok('unknown category falls back to Other', (await A.saveArt({ item: { title: 'X', category: 'nonsense' }, image: png })).find((x) => x.title === 'X').category === 'Other');
  ok('a new piece without a picture is refused', await rejects(A.saveArt({ item: { title: 'No pic' } })));
  ok('a non-image data URL is refused', await rejects(A.saveArt({ item: { title: 'Bad' }, image: 'data:text/html;base64,PHNjcmlwdD4=' })));
  ok('an oversized picture is refused', await rejects(A.saveArt({ item: { title: 'Big' }, image: 'data:image/png;base64,' + 'A'.repeat(A.MAX_IMG + 5) })));
  l = await A.saveArt({ item: { id: a.id, title: 'Renamed', category: 'Branding' } });
  const e = l.find((x) => x.id === a.id);
  ok('editing details keeps the picture and version', e.title === 'Renamed' && e.v === 1 && !!(await A.getArtImage(a.id, false)));
  l = await A.saveArt({ item: { id: a.id }, image: png });
  ok('replacing the picture bumps the version', l.find((x) => x.id === a.id).v === 2);
  const before = (await A.listArt()).map((x) => x.id);
  const after = (await A.moveArt(before[before.length - 1], 'up')).map((x) => x.id);
  ok('move up swaps neighbours', after[before.length - 2] === before[before.length - 1]);
  l = await A.deleteArt(a.id);
  ok('delete removes the piece and its pictures', !l.some((x) => x.id === a.id) && !(await A.getArtImage(a.id, false)));
  const c = await A.saveArt({ item: { title: 'Tint', category: 'Logos' }, image: png, color: '#FF8800', tone: 'nope' });
  const ci = c.find((x) => x.title === 'Tint');
  ok('colour is stored lower-case, bad tone falls back', ci.color === '#ff8800' && /^#[0-9a-f]{6}$/.test(ci.tone));
  const c2 = await A.saveArt({ item: { id: ci.id, title: 'Tint', category: 'Logos' }, color: '#00ff00', tone: '#101010' });
  ok('colours can be refreshed without a new picture', c2.find((x) => x.id === ci.id).color === '#00ff00' && c2.find((x) => x.id === ci.id).v === ci.v);
  await A.deleteArt(ci.id);
  ok('ids are sanitised', A.cleanId('../../etc/passwd') === 'etcpasswd');
  process.exit(fail ? 1 : 0);
})();
