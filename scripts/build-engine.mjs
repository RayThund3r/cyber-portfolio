// node scripts/build-engine.mjs
// Compiles engine/{core.js,app.js,app.css} into src/lib/builder/engine.generated.ts (so the browser preview and the
// server zip exporter emit EXACTLY the same, tested engine). Re-run after editing anything in /engine.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rd = (f) => readFileSync(join(root, 'engine', f), 'utf8');
const core = rd('core.js'), app = rd('app.js'), css = rd('app.css');
for (const [n, s] of [['core.js', core], ['app.js', app]]) {
  try { new Function(s); } catch (e) { console.error(`engine/${n} has a syntax error: ${e.message}`); process.exit(1); }
}
const out = `// AUTO-GENERATED by scripts/build-engine.mjs — DO NOT EDIT. Edit /engine/*.js|css and re-run the script.
export const ENGINE_VERSION = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
export const ENGINE_CORE_JS = ${JSON.stringify(core)};
export const ENGINE_APP_JS = ${JSON.stringify(app)};
export const ENGINE_CSS = ${JSON.stringify(css)};
`;
writeFileSync(join(root, 'src', 'lib', 'builder', 'engine.generated.ts'), out);
console.log(`engine compiled: core ${core.length} B · app ${app.length} B · css ${css.length} B`);
